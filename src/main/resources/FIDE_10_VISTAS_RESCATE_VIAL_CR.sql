-- VISTA 1: USUARIOS, TIPOS DE USUARIOS Y ESTADOS
-- DESCRIPCION: MOSTRAR LA INFORMACION GENERAL DE CADA USUARIO, SU TIPO Y ESTADO.
CREATE OR REPLACE VIEW FIDE_USUARIOS_TIPOS_ESTADOS_V AS
SELECT U.ID_USUARIO,
       U.NOMBRE,
       U.PRIMER_APELLIDO,
       U.SEGUNDO_APELLIDO,
       U.USERNAME,
       U.ID_TIPO_USUARIO,
       TU.NOMBRE_TIPO_USUARIO,
       U.ID_ESTADO,
       E.NOMBRE_ESTADO
FROM FIDE_USUARIOS_TB U
INNER JOIN FIDE_TIPOS_USUARIOS_TB TU
    ON U.ID_TIPO_USUARIO = TU.ID_TIPO_USUARIO
INNER JOIN FIDE_ESTADOS_TB E
    ON U.ID_ESTADO = E.ID_ESTADO;

-- VISTA 2: VEHICULOS Y PROPIETARIOS
-- DESCRIPCION: CONSULTAR VEHICULOS, SUS PROPIETARIOS, MARCAS, MODELOS Y ANIOS.
CREATE OR REPLACE VIEW FIDE_VEHICULOS_PROPIETARIOS_V AS
SELECT V.ID_VEHICULO,
       V.PLACA,
       V.CODIGO_CHASIS,
       U.ID_USUARIO AS ID_PROPIETARIO,
       U.NOMBRE AS NOMBRE_PROPIETARIO,
       U.PRIMER_APELLIDO AS PRIMER_APELLIDO_PROPIETARIO,
       U.SEGUNDO_APELLIDO AS SEGUNDO_APELLIDO_PROPIETARIO,
       M.NOMBRE_MARCA,
       MO.NOMBRE_MODELO,
       A.ANIO,
       E.NOMBRE_ESTADO AS ESTADO_VEHICULO
FROM FIDE_VEHICULOS_TB V
INNER JOIN FIDE_USUARIOS_TB U
    ON V.ID_USUARIO = U.ID_USUARIO
INNER JOIN FIDE_MARCAS_TB M
    ON V.ID_MARCA = M.ID_MARCA
INNER JOIN FIDE_MODELOS_TB MO
    ON V.ID_MARCA = MO.ID_MARCA
   AND V.ID_MODELO = MO.ID_MODELO
INNER JOIN FIDE_ANIOS_TB A
    ON V.ID_MODELO = A.ID_MODELO
   AND V.ID_ANIO = A.ID_ANIO
INNER JOIN FIDE_ESTADOS_TB E
    ON V.ID_ESTADO = E.ID_ESTADO;

-- VISTA 3: INCIDENTES DETALLADOS
-- DESCRIPCION: CONSULTAR LOS INCIDENTES CON VEHICULO, TIPO, PRIORIDAD Y ESTADO.
CREATE OR REPLACE VIEW FIDE_INCIDENTES_DETALLE_V AS
SELECT I.ID_INCIDENTE,
       I.FECHA_REPORTE,
       I.HORA_REPORTE,
       I.DETALLES_INCIDENTE,
       I.ID_USUARIO AS ID_USUARIO_REPORTA,
       V.ID_VEHICULO,
       V.PLACA,
       TI.NOMBRE_TIPO_INCIDENTE,
       PR.NOMBRE_PRIORIDAD,
       UI.ID_UBICACION_INCIDENTE,
       UI.OTRAS_SENAS,
       E.NOMBRE_ESTADO AS ESTADO_INCIDENTE
FROM FIDE_INCIDENTES_TB I
INNER JOIN FIDE_VEHICULOS_TB V
    ON I.ID_VEHICULO = V.ID_VEHICULO
INNER JOIN FIDE_TIPOS_INCIDENTES_TB TI
    ON I.ID_TIPO_INCIDENTE = TI.ID_TIPO_INCIDENTE
INNER JOIN FIDE_PRIORIDADES_TB PR
    ON I.ID_PRIORIDAD = PR.ID_PRIORIDAD
INNER JOIN FIDE_UBICACION_INCIDENTES_TB UI
    ON I.ID_UBICACION_INCIDENTE = UI.ID_UBICACION_INCIDENTE
INNER JOIN FIDE_ESTADOS_TB E
    ON I.ID_ESTADO = E.ID_ESTADO;

-- VISTA 4: UBICACIONES DE INCIDENTES
-- DESCRIPCION: MOSTRAR PROVINCIA, CANTON, DISTRITO Y OTRAS SENAS.
CREATE OR REPLACE VIEW FIDE_UBICACIONES_INCIDENTES_V AS
SELECT UI.ID_UBICACION_INCIDENTE,
       P.ID_PROVINCIA,
       P.NOMBRE_PROVINCIA,
       C.ID_CANTON,
       C.NOMBRE_CANTON,
       D.ID_DISTRITO,
       D.NOMBRE_DISTRITO,
       UI.OTRAS_SENAS
FROM FIDE_UBICACION_INCIDENTES_TB UI
INNER JOIN FIDE_PROVINCIAS_TB P
    ON UI.ID_PROVINCIA = P.ID_PROVINCIA
INNER JOIN FIDE_CANTONES_TB C
    ON UI.ID_CANTON = C.ID_CANTON
INNER JOIN FIDE_DISTRITOS_TB D
    ON UI.ID_DISTRITO = D.ID_DISTRITO;

-- VISTA 5: UNIDADES Y TIPOS DE UNIDADES
-- DESCRIPCION: CONSULTAR LAS UNIDADES, SU TIPO Y ESTADO REGISTRADO.
CREATE OR REPLACE VIEW FIDE_UNIDADES_DETALLE_V AS
SELECT U.ID_UNIDAD,
       U.NOMBRE_UNIDAD,
       U.ID_TIPO_UNIDAD,
       TU.NOMBRE_TIPO_UNIDAD,
       U.ID_ESTADO,
       E.NOMBRE_ESTADO AS ESTADO_UNIDAD
FROM FIDE_UNIDADES_TB U
INNER JOIN FIDE_TIPOS_UNIDADES_TB TU
    ON U.ID_TIPO_UNIDAD = TU.ID_TIPO_UNIDAD
INNER JOIN FIDE_ESTADOS_TB E
    ON U.ID_ESTADO = E.ID_ESTADO;

-- VISTA 6: HISTORIAL DE ASISTENCIAS
-- DESCRIPCION: CONSULTAR LAS SALIDAS Y REGRESOS DE UNIDADES POR INCIDENTE.
CREATE OR REPLACE VIEW FIDE_HISTORIAL_ASISTENCIAS_V AS
SELECT H.ID_HISTORIAL,
       H.ID_UNIDAD,
       U.NOMBRE_UNIDAD,
       H.ID_INCIDENTE,
       H.FECHA_SALIDA_UNIDAD,
       H.HORA_SALIDA_UNIDAD,
       H.FECHA_REGRESO_UNIDAD,
       H.HORA_REGRESO_UNIDAD,
       H.OBSERVACIONES,
       H.ID_RESPONSABLE,
       R.NOMBRE AS NOMBRE_RESPONSABLE,
       R.PRIMER_APELLIDO AS APELLIDO_RESPONSABLE,
       E.NOMBRE_ESTADO AS ESTADO_HISTORIAL
FROM FIDE_HISTORIALES_UNIDADES_TB H
INNER JOIN FIDE_UNIDADES_TB U
    ON H.ID_UNIDAD = U.ID_UNIDAD
INNER JOIN FIDE_INCIDENTES_TB I
    ON H.ID_INCIDENTE = I.ID_INCIDENTE
INNER JOIN FIDE_USUARIOS_TB R
    ON H.ID_RESPONSABLE = R.ID_USUARIO
INNER JOIN FIDE_ESTADOS_TB E
    ON H.ID_ESTADO = E.ID_ESTADO;

-- VISTA 7: REPARACIONES Y MECANICOS
-- DESCRIPCION: MOSTRAR REPARACIONES, INCIDENTES, MECANICOS Y ESTADOS.
CREATE OR REPLACE VIEW FIDE_REPARACIONES_DETALLE_V AS
SELECT R.ID_REPARACION,
       R.ID_INCIDENTE,
       I.ID_VEHICULO,
       R.DESCRIPCION_REPARACION,
       R.FECHA_INGRESO_TALLER,
       R.FECHA_INICIO_REPARACION,
       R.FECHA_FIN_REPARACION,
       R.HORAS_TRABAJADAS,
       R.COSTO_SERVICIO,
       R.ID_MECANICO,
       U.NOMBRE AS NOMBRE_MECANICO,
       U.PRIMER_APELLIDO AS APELLIDO_MECANICO,
       E.NOMBRE_ESTADO AS ESTADO_REPARACION
FROM FIDE_REPARACIONES_TB R
INNER JOIN FIDE_INCIDENTES_TB I
    ON R.ID_INCIDENTE = I.ID_INCIDENTE
INNER JOIN FIDE_USUARIOS_TB U
    ON R.ID_MECANICO = U.ID_USUARIO
INNER JOIN FIDE_ESTADOS_TB E
    ON R.ID_ESTADO = E.ID_ESTADO;

-- VISTA 8: REPUESTOS UTILIZADOS EN REPARACIONES
-- DESCRIPCION: MOSTRAR REPUESTOS, CANTIDADES Y PRECIOS APLICADOS.
CREATE OR REPLACE VIEW FIDE_REPUESTOS_REPARACIONES_V AS
SELECT DR.ID_REPARACION,
       R.ID_INCIDENTE,
       DR.ID_REPUESTO,
       RP.NOMBRE_REPUESTO,
       DR.CANTIDAD_REPUESTOS,
       DR.PRECIO_UNITARIO_APLICADO,
       DR.CANTIDAD_REPUESTOS * DR.PRECIO_UNITARIO_APLICADO AS SUBTOTAL_REPUESTO
FROM FIDE_DETALLE_REPARACIONES_TB DR
INNER JOIN FIDE_REPARACIONES_TB R
    ON DR.ID_REPARACION = R.ID_REPARACION
INNER JOIN FIDE_REPUESTOS_TB RP
    ON DR.ID_REPUESTO = RP.ID_REPUESTO;

-- VISTA 9: PAGOS Y FACTURACION
-- DESCRIPCION: MOSTRAR LOS PAGOS REGISTRADOS CON SU FACTURA Y METODO DE PAGO.
-- NOTA: AL UTILIZAR INNER JOIN, SOLO MUESTRA FACTURAS QUE TIENEN PAGOS.
CREATE OR REPLACE VIEW FIDE_PAGOS_FACTURACION_V AS
SELECT P.ID_FACTURA,
       P.ID_PAGO,
       F.FECHA_FACTURA,
       F.TOTAL_FACTURA,
       V.ID_VENTA,
       V.ID_INCIDENTE,
       P.FECHA_PAGO,
       P.MONTO_APORTADO,
       MP.NOMBRE_METODO_PAGO,
       E.NOMBRE_ESTADO AS ESTADO_PAGO
FROM FIDE_PAGOS_TB P
INNER JOIN FIDE_FACTURAS_TB F
    ON P.ID_FACTURA = F.ID_FACTURA
INNER JOIN FIDE_VENTAS_TB V
    ON F.ID_VENTA = V.ID_VENTA
INNER JOIN FIDE_METODOS_PAGO_TB MP
    ON P.ID_METODO_PAGO = MP.ID_METODO_PAGO
INNER JOIN FIDE_ESTADOS_TB E
    ON P.ID_ESTADO = E.ID_ESTADO;

-- VISTA 10: TARIFAS POR TIPO DE UNIDAD
-- DESCRIPCION: MOSTRAR TARIFAS, TIPOS DE UNIDADES Y ESTADOS.
CREATE OR REPLACE VIEW FIDE_TARIFAS_UNIDADES_V AS
SELECT T.ID_TARIFA,
       T.ID_TIPO_UNIDAD,
       TU.NOMBRE_TIPO_UNIDAD,
       T.PRECIO_KILOMETRO,
       T.MONTO_MINIMO,
       T.FECHA_ACTUALIZACION,
       E.NOMBRE_ESTADO AS ESTADO_TARIFA
FROM FIDE_TARIFAS_TB T
INNER JOIN FIDE_TIPOS_UNIDADES_TB TU
    ON T.ID_TIPO_UNIDAD = TU.ID_TIPO_UNIDAD
INNER JOIN FIDE_ESTADOS_TB E
    ON T.ID_ESTADO = E.ID_ESTADO;

