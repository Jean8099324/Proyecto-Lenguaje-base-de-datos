--- PROCEDIMIENTO PARA ASIGNAR UN ROL A UN USUARIO
PROCEDURE FIDE_ASIGNAR_ROL_A_USUARIO_SP(
    P_ID_USUARIO IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.ID_USUARIO%TYPE,
    P_ID_ROL IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_ROLES_TB.ID_ROL%TYPE)
IS
    V_ID_ESTADO NUMBER;
BEGIN
    SELECT ID_ESTADO
    INTO V_ID_ESTADO
    FROM PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_ROLES_TB
    WHERE ID_USUARIO = P_ID_USUARIO
    AND ID_ROL = P_ID_ROL;
    IF V_ID_ESTADO = 2 THEN
        UPDATE PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_ROLES_TB
        SET ID_ESTADO = 1
        WHERE ID_USUARIO = P_ID_USUARIO
        AND ID_ROL = P_ID_ROL;
        DBMS_OUTPUT.PUT_LINE('ROL REACTIVADO CORRECTAMENTE');
    ELSIF V_ID_ESTADO = 1 THEN
        DBMS_OUTPUT.PUT_LINE('EL USUARIO YA TIENE EL ROL ASIGNADO');
    ELSE
        DBMS_OUTPUT.PUT_LINE('EL ROL TIENE OTRO ESTADO');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        INSERT INTO PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_ROLES_TB(
            ID_USUARIO,
            ID_ROL,
            ID_ESTADO
        )
        VALUES(
            P_ID_USUARIO,
            P_ID_ROL,
            1
        );
        DBMS_OUTPUT.PUT_LINE('ROL ASIGNADO CORRECTAMENTE');
    WHEN TOO_MANY_ROWS THEN
        DBMS_OUTPUT.PUT_LINE('SE ENCONTRARON DEMASIADOS REGISTROS');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERROR: ' || SQLERRM);
END FIDE_ASIGNAR_ROL_A_USUARIO_SP;

