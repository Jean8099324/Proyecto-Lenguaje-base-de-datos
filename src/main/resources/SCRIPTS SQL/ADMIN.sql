/* VERIFICACION DE USUARIO ADMINISTRADOR
   DESCRIPCION: CONFIRMAR EL USUARIO
   Y LOS PRIVILEGIOS ADMINISTRATIVOS
*/
SELECT USER AS USUARIO_ACTUAL
FROM DUAL;

SELECT PRIVILEGE
FROM SESSION_PRIVS
WHERE PRIVILEGE IN ('CREATE ROLE', 'CREATE USER', 'GRANT ANY ROLE', 'GRANT ANY PRIVILEGE')
ORDER BY PRIVILEGE;

/* VERIFICACION DE ROLES DEL PROYECTO
   DESCRIPCION: COMPROBAR SI EXISTEN
   ROLES ESPECIFICOS DE RESCATE VIAL CR
*/
SELECT ROLE
FROM DBA_ROLES
WHERE ROLE IN ('FIDE_RESCATE_ADMIN', 'FIDE_RESCATE_REGISTRO', 'FIDE_RESCATE_CONSULTA')
ORDER BY ROLE;

/* CREACION DE ROLES DE SEGURIDAD
   DESCRIPCION: CREAR LOS ROLES PARA
   EL CONTROL DE ACCESO A RESCATE VIAL CR
*/
-- ROL ADMINISTRATIVO DEL PROYECTO
CREATE ROLE FIDE_RESCATE_ADMIN;

-- ROL PARA REGISTRO DE INFORMACION
CREATE ROLE FIDE_RESCATE_REGISTRO;

-- ROL PARA CONSULTA DE INFORMACION
CREATE ROLE FIDE_RESCATE_CONSULTA;

/* VERIFICACION DE ROLES
   DESCRIPCION: CONFIRMAR LA CREACION
   DE LOS TRES ROLES DEL PROYECTO
*/
SELECT ROLE
FROM DBA_ROLES
WHERE ROLE IN ('FIDE_RESCATE_ADMIN', 'FIDE_RESCATE_REGISTRO', 'FIDE_RESCATE_CONSULTA')
ORDER BY ROLE;

/* ASIGNACION DE PERMISOS DE CONSULTA
   DESCRIPCION: PERMITIR CONSULTAR
   INFORMACION DEL SISTEMA DE FACTURACION
*/

-- CONSULTAR PROFORMAS
GRANT SELECT ON FIDE_PROFORMAS_TB
TO FIDE_RESCATE_CONSULTA;

-- CONSULTAR VENTAS
GRANT SELECT ON FIDE_VENTAS_TB
TO FIDE_RESCATE_CONSULTA;

-- CONSULTAR FACTURAS
GRANT SELECT ON FIDE_FACTURAS_TB
TO FIDE_RESCATE_CONSULTA;

-- CONSULTAR PAGOS
GRANT SELECT ON FIDE_PAGOS_TB
TO FIDE_RESCATE_CONSULTA;




