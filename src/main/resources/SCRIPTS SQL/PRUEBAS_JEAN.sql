/* CONSULTA DE FACTURAS PARA PRUEBAS
   DESCRIPCION: BUSCAR FACTURAS ACTIVAS
   CON SALDO PENDIENTE SIN UTILIZAR
   LA VENTA HISTORICA 1
*/
SELECT F.ID_FACTURA, F.ID_VENTA, F.TOTAL_FACTURA,
       NVL(SUM(CASE WHEN P.ID_ESTADO = 1 THEN P.MONTO_APORTADO ELSE 0 END), 0) AS TOTAL_PAGADO,
       F.TOTAL_FACTURA -
       NVL(SUM(CASE WHEN P.ID_ESTADO = 1 THEN P.MONTO_APORTADO ELSE 0 END), 0) AS SALDO_PENDIENTE
FROM FIDE_FACTURAS_TB F
LEFT JOIN FIDE_PAGOS_TB P
    ON F.ID_FACTURA = P.ID_FACTURA
WHERE F.ID_ESTADO = 1
AND F.ID_VENTA <> 1
GROUP BY F.ID_FACTURA, F.ID_VENTA, F.TOTAL_FACTURA
HAVING F.TOTAL_FACTURA -
       NVL(SUM(CASE WHEN P.ID_ESTADO = 1 THEN P.MONTO_APORTADO ELSE 0 END), 0) >= 1000
ORDER BY F.ID_FACTURA;

