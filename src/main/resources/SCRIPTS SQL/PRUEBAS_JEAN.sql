/* VERIFICACION DE RESTRICCIONES DE TABLAS
   DESCRIPCION: IDENTIFICAR LLAVES PRIMARIAS,
   FORANEAS, UNICAS Y RESTRICCIONES CHECK
   PARA REALIZAR PRUEBAS DE INSERCION SEGURAS
*/

SELECT C.TABLE_NAME,
       C.CONSTRAINT_NAME,
       C.CONSTRAINT_TYPE,
       CC.COLUMN_NAME,
       C.STATUS,
       C.VALIDATED
FROM USER_CONSTRAINTS C
INNER JOIN USER_CONS_COLUMNS CC
    ON C.CONSTRAINT_NAME = CC.CONSTRAINT_NAME
   AND C.TABLE_NAME = CC.TABLE_NAME
WHERE C.TABLE_NAME IN ('FIDE_VENTAS_TB', 'FIDE_PAGOS_TB', 'FIDE_METODOS_PAGO_TB', 'FIDE_FACTURAS_TB')
