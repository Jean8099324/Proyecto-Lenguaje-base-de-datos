/* VERIFICACION DEL TRIGGER DE PAGOS
   DESCRIPCION: COMPROBAR SU COMPILACION
   Y QUE CONTINUE HABILITADO
*/

SELECT O.OBJECT_NAME,
       O.STATUS AS ESTADO_COMPILACION,
       T.STATUS AS ESTADO_TRIGGER
FROM USER_OBJECTS O
INNER JOIN USER_TRIGGERS T
    ON O.OBJECT_NAME = T.TRIGGER_NAME
WHERE O.OBJECT_NAME = 'FIDE_PAGOS_INSERT_TRG'
AND O.OBJECT_TYPE = 'TRIGGER';





