--- ELIMINANDO TODAS LAS SECUENCIAS EXISTENTES.
BEGIN
  FOR s IN (
    SELECT sequence_name
    FROM user_sequences
  ) LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE "' || s.sequence_name || '"';
  END LOOP;
END;
