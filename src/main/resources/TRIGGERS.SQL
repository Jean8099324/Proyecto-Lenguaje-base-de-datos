BEFORE INSERT ON PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_METODOS_PAGO_TB
FOR EACH ROW
BEGIN
    :NEW.CREADO_POR:= SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER');
    :NEW.FECHA_CREACION:= SYSTIMESTAMP AT TIME ZONE 'UTC';
    :NEW.ACCION:= 'INSERT';
    :NEW.ID_METODO_PAGO:= PROYECTO_FINAL_RESCATE_VIAL_CR.ID_METODO_PAGO_SEQ.NEXTVAL;
    EXCEPTION
        WHEN TOO_MANY_ROWS THEN
            DBMS_OUTPUT.PUT_LINE('SE ENCONTRARON DEMASIADOS REGISTROS');
            WHEN NO_DATA_FOUND THEN
                DBMS_OUTPUT.PUT_LINE('NO SE ENCONTRARON DATOS');
                WHEN OTHERS THEN
                    DBMS_OUTPUT.PUT_LINE('ERROR: ' || SQLERRM);
END FIDE_METODOS_PAGO_INSERT_TRG;
/
