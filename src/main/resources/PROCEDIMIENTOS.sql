CREATE OR REPLACE PROCEDURE FIDE_INSERTAR_USUARIOS_SP(
P_ID_USUARIO IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.ID_USUARIO%TYPE,
P_NOMBRE IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.NOMBRE%TYPE,
P_PRIMER_APELLIDO IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.PRIMER_APELLIDO%TYPE,
P_SEGUNDO_APELLIDO IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.SEGUNDO_APELLIDO%TYPE,
P_FECHA_NACIMIENTO IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.FECHA_NACIMIENTO%TYPE,
P_USERNAME IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.USERNAME%TYPE,
P_PASSWORD IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.PASSWORD%TYPE,
P_FECHA_CREACION IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.FECHA_CREACION%TYPE,
P_FECHA_MODIFICACION IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.FECHA_MODIFICACION%TYPE,
P_FECHA_ELIMINACION IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.FECHA_ELIMINACION%TYPE,
P_TIPO_USUARIO IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.ID_TIPO_USUARIO%TYPE,
P_ESTADO IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.ID_ESTADO%TYPE
) IS
BEGIN
    INSERT INTO FIDE_USUARIOS_TB(
        ID_USUARIO,
        NOMBRE,
        PRIMER_APELLIDO,
        SEGUNDO_APELLIDO,
        FECHA_NACIMIENTO,
        USERNAME,
        PASSWORD,
        FECHA_CREACION,
        FECHA_MODIFICACION,
        FECHA_ELIMINACION,
        ID_TIPO_USUARIO,
        ID_ESTADO
    )
    VALUES(
        P_ID_USUARIO,
        P_NOMBRE,
        P_PRIMER_APELLIDO,
        P_SEGUNDO_APELLIDO,
        P_FECHA_NACIMIENTO,
        P_USERNAME,
        P_PASSWORD,
        P_FECHA_CREACION,
        P_FECHA_MODIFICACION,
        P_FECHA_ELIMINACION,
        P_TIPO_USUARIO,
        P_ESTADO
    );
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('ERROR: ' || SQLERRM);
            RAISE;
END FIDE_INSERTAR_USUARIOS_SP;

  SELECT SYS_CONTEXT('USERENV', 'SERVICE_NAME') FROM DUAL;
