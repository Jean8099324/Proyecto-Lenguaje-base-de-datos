    AND ur.ID_ESTADO = 1
    AND r.ID_ESTADO = 1;
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('ERROR: ' || SQLERRM);
END FIDE_OBTENER_ROLES_ACTIVOS_POR_ID_USUARIO_SP;
