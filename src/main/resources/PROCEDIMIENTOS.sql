--- PROCEDIMIENTO PARA OBTENER USUARIOS POR ESTADO MEDIANTE UN SYS_REFCURSOR
CREATE OR REPLACE PROCEDURE FIDE_OBTENER_USUARIOS_ACTIVOS_SP(
    P_RESULTADO OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_RESULTADO FOR
    SELECT u.ID_USUARIO,
           u.NOMBRE,
           u.PRIMER_APELLIDO,
           u.SEGUNDO_APELLIDO,
           u.FECHA_NACIMIENTO,
           u.USERNAME,
           u.PASSWORD,
           u.FECHA_CREACION,
           u.FECHA_MODIFICACION,
           u.FECHA_ELIMINACION,
           u.ID_TIPO_USUARIO,
           t.NOMBRE_TIPO_USUARIO,
           u.ID_ESTADO,
           e.NOMBRE_ESTADO
    FROM FIDE_USUARIOS_TB u, FIDE_TIPOS_USUARIOS_TB t, FIDE_ESTADOS_TB e
    WHERE u.ID_TIPO_USUARIO = t.ID_TIPO_USUARIO
    AND u.ID_ESTADO = e.ID_ESTADO
    AND u.ID_ESTADO = 1
    ORDER BY u.ID_USUARIO;
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('ERROR: ' || SQLERRM);
END FIDE_OBTENER_USUARIOS_ACTIVOS_SP;
