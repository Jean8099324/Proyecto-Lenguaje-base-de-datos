--- PROCEDIMIENTO PARA OBTENER SI EXISTE O NO UN USUARIO POR USERNAME
CREATE OR REPLACE PROCEDURE FIDE_EXISTE_POR_USERNAME_SP(
    P_USERNAME IN PROYECTO_FINAL_RESCATE_VIAL_CR.FIDE_USUARIOS_TB.USERNAME%TYPE,
    P_RESULTADO OUT NUMBER
) IS
    V_COUNT INTEGER := 0;
BEGIN
    SELECT COUNT(*)
    INTO V_COUNT
    FROM FIDE_USUARIOS_TB
    WHERE USERNAME = P_USERNAME;

    IF V_COUNT > 0 THEN
        P_RESULTADO := 1;
    ELSE
        P_RESULTADO := 0;
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERROR: ' || SQLERRM);
END FIDE_EXISTE_POR_USERNAME_SP;
