-- Restaurar las FK eliminadas por CASCADE CONSTRAINTS.
ALTER TABLE FIDE_INCIDENTES_CONTACTOS_TB
    ADD CONSTRAINT FIDE_INCIDENTES_CONTACTOS_ID_INCIDENTE_FK
        FOREIGN KEY(ID_INCIDENTE) REFERENCES FIDE_INCIDENTES_TB(ID_INCIDENTE);

ALTER TABLE FIDE_HISTORIALES_UNIDADES_TB
    ADD CONSTRAINT FIDE_HISTORIALES_UNIDADES_ID_INCIDENTE_FK
        FOREIGN KEY(ID_INCIDENTE) REFERENCES FIDE_INCIDENTES_TB(ID_INCIDENTE);

ALTER TABLE FIDE_REPARACIONES_TB
    ADD CONSTRAINT FIDE_REPARACIONES_ID_INCIDENTE_FK
        FOREIGN KEY(ID_INCIDENTE) REFERENCES FIDE_INCIDENTES_TB(ID_INCIDENTE);

ALTER TABLE FIDE_VENTAS_TB
    ADD CONSTRAINT FIDE_VENTAS_ID_INCIDENTE_FK
        FOREIGN KEY(ID_INCIDENTE) REFERENCES FIDE_INCIDENTES_TB(ID_INCIDENTE);

