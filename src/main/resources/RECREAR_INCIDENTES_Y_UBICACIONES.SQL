-- ATENCION: elimina todos los registros de incidentes y ubicaciones.
-- No elimina ni modifica FIDE_DIRECCIONES_TB.
-- Ejecutar con F5 (Run Script) como PROYECTO_FINAL_RESCATE_VIAL_CR.

SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

-- Las tablas que dependen de incidentes deben estar vacias. Si contienen datos,
-- el script se detiene para no dejarlos sin su incidente relacionado.
DECLARE
    V_DEPENDENCIAS NUMBER;
BEGIN
    SELECT (SELECT COUNT(*) FROM FIDE_INCIDENTES_CONTACTOS_TB)
         + (SELECT COUNT(*) FROM FIDE_HISTORIALES_UNIDADES_TB)
         + (SELECT COUNT(*) FROM FIDE_REPARACIONES_TB)
         + (SELECT COUNT(*) FROM FIDE_VENTAS_TB)
      INTO V_DEPENDENCIAS
      FROM DUAL;

    IF V_DEPENDENCIAS > 0 THEN
        RAISE_APPLICATION_ERROR(-20010,
            'No se pueden recrear las tablas: existen ' || V_DEPENDENCIAS ||
            ' registros dependientes en contactos, historiales, reparaciones o ventas.');
    END IF;
END;
/

-- El orden funciona tanto con el modelo anterior como con el nuevo.
DROP TABLE FIDE_INCIDENTES_TB CASCADE CONSTRAINTS PURGE;
DROP TABLE FIDE_UBICACION_INCIDENTES_TB CASCADE CONSTRAINTS PURGE;

-- La secuencia de ubicaciones ya no se utiliza.
BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE ID_UBICACION_INCIDENTE_SEQ';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -2289 THEN
            RAISE;
        END IF;
END;
/

CREATE TABLE FIDE_INCIDENTES_TB(
    ID_INCIDENTE NUMBER
        CONSTRAINT FIDE_INCIDENTES_ID_INCIDENTE_PK PRIMARY KEY,
    ID_VEHICULO NUMBER
        CONSTRAINT FIDE_INCIDENTES_ID_VEHICULO_NOT_NULL NOT NULL,
    FECHA_REPORTE DATE,
    HORA_REPORTE VARCHAR2(10),
    DETALLES_INCIDENTE VARCHAR2(500),
    FECHA_CIERRE DATE,
    HORA_CIERRE VARCHAR2(10),
    ID_TIPO_INCIDENTE NUMBER
        CONSTRAINT FIDE_INCIDENTES_ID_TIPO_INCIDENTE_NOT_NULL NOT NULL,
    ID_PRIORIDAD NUMBER
        CONSTRAINT FIDE_INCIDENTES_ID_PRIORIDAD_NOT_NULL NOT NULL,
    ID_ESTADO NUMBER
        CONSTRAINT FIDE_INCIDENTES_ID_ESTADO_NOT_NULL NOT NULL,
    ID_USUARIO NUMBER,
    CREADO_POR VARCHAR2(100),
    MODIFICADO_POR VARCHAR2(100),
    ACCION VARCHAR2(100),
    FECHA_CREACION TIMESTAMP(6),
    FECHA_MODIFICACION TIMESTAMP(6),

    CONSTRAINT FIDE_INCIDENTES_ID_VEHICULO_FK
        FOREIGN KEY(ID_VEHICULO) REFERENCES FIDE_VEHICULOS_TB(ID_VEHICULO),
    CONSTRAINT FIDE_INCIDENTES_ID_TIPO_INCIDENTE_FK
        FOREIGN KEY(ID_TIPO_INCIDENTE) REFERENCES FIDE_TIPOS_INCIDENTES_TB(ID_TIPO_INCIDENTE),
    CONSTRAINT FIDE_INCIDENTES_ID_PRIORIDAD_FK
        FOREIGN KEY(ID_PRIORIDAD) REFERENCES FIDE_PRIORIDADES_TB(ID_PRIORIDAD),
    CONSTRAINT FIDE_INCIDENTES_ID_ESTADO_FK
        FOREIGN KEY(ID_ESTADO) REFERENCES FIDE_ESTADOS_TB(ID_ESTADO),
    CONSTRAINT FIDE_INCIDENTES_ID_USUARIO_FK
        FOREIGN KEY(ID_USUARIO) REFERENCES FIDE_USUARIOS_TB(ID_USUARIO)
);

CREATE TABLE FIDE_UBICACION_INCIDENTES_TB(
    ID_INCIDENTE NUMBER,
    ID_PROVINCIA NUMBER,
    ID_CANTON NUMBER,
    ID_DISTRITO NUMBER,
    OTRAS_SENAS VARCHAR2(200),
    ID_ESTADO NUMBER
        CONSTRAINT FIDE_UBICACION_INCIDENTES_ID_ESTADO_NOT_NULL NOT NULL,
    CREADO_POR VARCHAR2(100),
    MODIFICADO_POR VARCHAR2(100),
    ACCION VARCHAR2(100),
    FECHA_CREACION TIMESTAMP(6),
    FECHA_MODIFICACION TIMESTAMP(6),

    CONSTRAINT FIDE_UBICACION_INCIDENTES_PK
        PRIMARY KEY(ID_INCIDENTE, ID_PROVINCIA, ID_CANTON, ID_DISTRITO),
    CONSTRAINT FIDE_UBICACION_INCIDENTES_ID_INCIDENTE_FK
        FOREIGN KEY(ID_INCIDENTE) REFERENCES FIDE_INCIDENTES_TB(ID_INCIDENTE),
    CONSTRAINT FIDE_UBICACION_INCIDENTES_ID_PROVINCIA_FK
        FOREIGN KEY(ID_PROVINCIA) REFERENCES FIDE_PROVINCIAS_TB(ID_PROVINCIA),
    CONSTRAINT FIDE_UBICACION_INCIDENTES_ID_CANTON_FK
        FOREIGN KEY(ID_CANTON) REFERENCES FIDE_CANTONES_TB(ID_CANTON),
    CONSTRAINT FIDE_UBICACION_INCIDENTES_ID_DISTRITO_FK
        FOREIGN KEY(ID_DISTRITO) REFERENCES FIDE_DISTRITOS_TB(ID_DISTRITO),
    CONSTRAINT FIDE_UBICACION_INCIDENTES_ID_ESTADO_FK
        FOREIGN KEY(ID_ESTADO) REFERENCES FIDE_ESTADOS_TB(ID_ESTADO)
